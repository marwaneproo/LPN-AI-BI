/* LPN AI-BI - Vente 2025 + 2026 export
   Oracle/Compiere source database, Oracle 11g compatible.

   Target period:
     from DATE '2025-01-01' inclusive
     to   DATE '2026-07-01' exclusive

   Export each block separately using the filename in the comment.
   For heavy line tables, export as CSV and keep the quarter suffix.

   Performance rules:
   - No function is applied to date columns in WHERE clauses.
   - Heavy line tables are driven by materialized header IDs.
   - Huge line exports avoid ORDER BY to reduce sort cost.
*/

/* 00_CONTROL_COUNTS_BY_QUARTER.csv */
WITH periods AS (
    SELECT '2025_Q1' AS period_name, DATE '2025-01-01' AS date_from, DATE '2025-04-01' AS date_to FROM DUAL UNION ALL
    SELECT '2025_Q2', DATE '2025-04-01', DATE '2025-07-01' FROM DUAL UNION ALL
    SELECT '2025_Q3', DATE '2025-07-01', DATE '2025-10-01' FROM DUAL UNION ALL
    SELECT '2025_Q4', DATE '2025-10-01', DATE '2026-01-01' FROM DUAL UNION ALL
    SELECT '2026_Q1', DATE '2026-01-01', DATE '2026-04-01' FROM DUAL UNION ALL
    SELECT '2026_Q2', DATE '2026-04-01', DATE '2026-07-01' FROM DUAL
),
order_counts AS (
    SELECT p.period_name, COUNT(o.C_ORDER_ID) AS order_count
    FROM periods p
    LEFT JOIN C_ORDER o
        ON o.DATEORDERED >= p.date_from
       AND o.DATEORDERED < p.date_to
       AND o.ISSOTRX = 'Y'
       AND o.DOCSTATUS IN ('CO', 'CL')
       AND o.C_DOCTYPETARGET_ID IN (1000028, 1000034, 1000032, 1000031)
    GROUP BY p.period_name
),
invoice_counts AS (
    SELECT p.period_name, COUNT(i.C_INVOICE_ID) AS invoice_count
    FROM periods p
    LEFT JOIN C_INVOICE i
        ON i.DATEINVOICED >= p.date_from
       AND i.DATEINVOICED < p.date_to
       AND i.ISSOTRX = 'Y'
       AND i.DOCSTATUS = 'CO'
       AND i.C_DOCTYPE_ID IN (1000002, 1000003, 1000004)
    GROUP BY p.period_name
),
delivery_counts AS (
    SELECT p.period_name, COUNT(io.M_INOUT_ID) AS delivery_count
    FROM periods p
    LEFT JOIN M_INOUT io
        ON io.MOVEMENTDATE >= p.date_from
       AND io.MOVEMENTDATE < p.date_to
       AND io.ISSOTRX = 'Y'
       AND io.DOCSTATUS IN ('CO', 'CL')
    GROUP BY p.period_name
)
SELECT
    p.period_name,
    p.date_from,
    p.date_to,
    oc.order_count,
    ic.invoice_count,
    dc.delivery_count
FROM periods p
LEFT JOIN order_counts oc ON oc.period_name = p.period_name
LEFT JOIN invoice_counts ic ON ic.period_name = p.period_name
LEFT JOIN delivery_counts dc ON dc.period_name = p.period_name
ORDER BY p.date_from;

