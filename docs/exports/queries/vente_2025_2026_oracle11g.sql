/* 42_CORRECTED_CUSTOMER_PORTFOLIO_2025_2026.csv
   This replaces the unreliable 57_COMMERCIAL_CUSTOMER_PORTFOLIO_24M CA logic.
   Orders and invoices are aggregated separately, then joined to customers.
*/
WITH order_agg AS (
    SELECT
        o.C_BPARTNER_ID,
        COUNT(*) AS ORDER_COUNT,
        MIN(o.DATEORDERED) AS FIRST_ORDER_DATE,
        MAX(o.DATEORDERED) AS LAST_ORDER_DATE,
        SUM(o.GRANDTOTAL) AS ORDERED_CA_TTC
    FROM C_ORDER o
    WHERE o.DATEORDERED >= DATE '2025-01-01'
      AND o.DATEORDERED < DATE '2026-07-01'
      AND o.ISSOTRX = 'Y'
      AND o.DOCSTATUS IN ('CO', 'CL')
      AND o.C_DOCTYPETARGET_ID IN (1000028, 1000034, 1000032, 1000031)
    GROUP BY o.C_BPARTNER_ID
),
invoice_agg AS (
    SELECT
        i.C_BPARTNER_ID,
        COUNT(*) AS INVOICE_COUNT,
        MIN(i.DATEINVOICED) AS FIRST_INVOICE_DATE,
        MAX(i.DATEINVOICED) AS LAST_INVOICE_DATE,
        SUM(i.GRANDTOTAL) AS INVOICED_CA_TTC,
        SUM(CASE WHEN i.ISPAID = 'Y' THEN i.GRANDTOTAL ELSE 0 END) AS PAID_CA_TTC,
        SUM(CASE WHEN NVL(i.ISPAID, 'N') <> 'Y' THEN i.GRANDTOTAL ELSE 0 END) AS UNPAID_CA_TTC
    FROM C_INVOICE i
    WHERE i.DATEINVOICED >= DATE '2025-01-01'
      AND i.DATEINVOICED < DATE '2026-07-01'
      AND i.ISSOTRX = 'Y'
      AND i.DOCSTATUS = 'CO'
      AND i.C_DOCTYPE_ID IN (1000002, 1000003, 1000004)
    GROUP BY i.C_BPARTNER_ID
),
selected_customers AS (
    SELECT C_BPARTNER_ID FROM order_agg
    UNION
    SELECT C_BPARTNER_ID FROM invoice_agg
)
SELECT
    bp.C_BPARTNER_ID,
    bp.VALUE AS CUSTOMER_CODE,
    bp.NAME AS CUSTOMER_NAME,
    bp.NAME2 AS CUSTOMER_NAME2,
    bp.ISCUSTOMER,
    bp.ISVENDOR,
    bp.C_BP_GROUP_ID,
    bg.NAME AS BP_GROUP_NAME,
    bp.SALESREP_ID,
    au.NAME AS SALESREP_NAME,
    bp.C_PAYMENTTERM_ID,
    pt.NAME AS PAYMENTTERM_NAME,
    bp.M_PRICELIST_ID,
    pl.NAME AS PRICELIST_NAME,
    bp.SO_CREDITLIMIT,
    bp.SO_CREDITUSED,
    bp.TOTALOPENBALANCE,
    oa.ORDER_COUNT,
    oa.FIRST_ORDER_DATE,
    oa.LAST_ORDER_DATE,
    oa.ORDERED_CA_TTC,
    ia.INVOICE_COUNT,
    ia.FIRST_INVOICE_DATE,
    ia.LAST_INVOICE_DATE,
    ia.INVOICED_CA_TTC,
    ia.PAID_CA_TTC,
    ia.UNPAID_CA_TTC
FROM selected_customers sc
JOIN C_BPARTNER bp ON bp.C_BPARTNER_ID = sc.C_BPARTNER_ID
LEFT JOIN order_agg oa ON oa.C_BPARTNER_ID = bp.C_BPARTNER_ID
LEFT JOIN invoice_agg ia ON ia.C_BPARTNER_ID = bp.C_BPARTNER_ID
LEFT JOIN C_BP_GROUP bg ON bg.C_BP_GROUP_ID = bp.C_BP_GROUP_ID
LEFT JOIN AD_USER au ON au.AD_USER_ID = bp.SALESREP_ID
LEFT JOIN C_PAYMENTTERM pt ON pt.C_PAYMENTTERM_ID = bp.C_PAYMENTTERM_ID
LEFT JOIN M_PRICELIST pl ON pl.M_PRICELIST_ID = bp.M_PRICELIST_ID
ORDER BY NVL(ia.INVOICED_CA_TTC, 0) DESC, NVL(oa.ORDERED_CA_TTC, 0) DESC, bp.C_BPARTNER_ID;
